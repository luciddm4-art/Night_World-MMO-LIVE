// Cache-busting without a build step.
//
// GitHub Pages lets browsers keep files for ~10 minutes, and ES modules are cached even harder,
// so after a deploy players could run a mix of old and new scripts. This script gives every
// script a version taken from its own contents and writes an import map into index.html:
//
//   "./src/fx.js" -> "./src/fx.js?v=1a2b3c4d"
//
// A changed file gets a new URL (fetched fresh); an unchanged file keeps its URL (stays cached).
//
//   npm run stamp           update index.html
//   npm run stamp -- --check   fail if index.html is out of date (CI + tests use this)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const hash = (f) => crypto.createHash('sha1').update(fs.readFileSync(path.join(ROOT, f))).digest('hex').slice(0, 8);

export function buildStamped(html) {
  const imports = {};
  for (const dir of ['src', 'shared']) {
    for (const f of fs.readdirSync(path.join(ROOT, dir)).filter((n) => n.endsWith('.js')).sort()) {
      const rel = dir + '/' + f;
      imports['./' + rel] = './' + rel + '?v=' + hash(rel);
    }
  }
  const map = '<!-- importmap:start (generated by tools/stamp.mjs; run `npm run stamp`) -->\n'
    + '<script type="importmap">\n' + JSON.stringify({ imports }, null, 1) + '\n</script>\n'
    + '<!-- importmap:end -->';
  let out = html;
  if (/<!-- importmap:start[\s\S]*?<!-- importmap:end -->/.test(out)) {
    out = out.replace(/<!-- importmap:start[\s\S]*?<!-- importmap:end -->/, () => map);
  } else {
    out = out.replace('<link rel="stylesheet"', () => map + '\n<link rel="stylesheet"');
  }
  out = out.replace(/href="css\/style\.css[^"]*"/, 'href="css/style.css?v=' + hash('css/style.css') + '"');
  out = out.replace(/src="src\/boot\.js[^"]*"/, 'src="src/boot.js?v=' + hash('src/boot.js') + '"');
  return out;
}

export function isStamped() {
  const file = path.join(ROOT, 'index.html');
  const html = fs.readFileSync(file, 'utf8');
  return buildStamped(html) === html;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = path.join(ROOT, 'index.html');
  const html = fs.readFileSync(file, 'utf8');
  const next = buildStamped(html);
  if (process.argv.includes('--check')) {
    if (next !== html) { console.error('index.html is out of date. Run: npm run stamp'); process.exit(1); }
    console.log('index.html is up to date');
  } else {
    fs.writeFileSync(file, next);
    console.log(next === html ? 'index.html already up to date' : 'index.html updated');
  }
}
